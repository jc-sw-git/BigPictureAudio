/// Language for a stored code; `None` (or an unknown code) follows Windows.
pub fn resolve(code: Option<&str>) -> &'static Texts {
    code.and_then(|code| LANGUAGES.iter().find(|t| t.code == code))
        .unwrap_or_else(windows_language)
}

/// The Windows display language, falling back to English.
fn windows_language() -> &'static Texts {
    let primary = unsafe { GetUserDefaultUILanguage() } & 0x3ff;
    LANGUAGES
        .iter()
        .find(|t| t.primary_lang_id == primary)
        .unwrap_or(&LANGUAGES[0])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn codes_and_lang_ids_are_unique() {
        for (i, a) in LANGUAGES.iter().enumerate() {
            for b in &LANGUAGES[i + 1..] {
                assert_ne!(a.code, b.code);
                assert_ne!(a.primary_lang_id, b.primary_lang_id);
            }
        }
    }

    #[test]
    fn resolves_codes() {
        assert_eq!(resolve(Some("tr")).code, "tr");
        // Unknown codes fall back to the Windows language, which is always one of ours.
        assert!(LANGUAGES.iter().any(|t| t.code == resolve(Some("xx")).code));
    }
}
